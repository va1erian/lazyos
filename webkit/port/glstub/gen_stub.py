#!/usr/bin/env python3
"""Generate the sources of ``libEGL.a`` and ``libGLESv2.a`` from the Khronos headers.

LazyOS has no GPU, no display server and no EGL. WebKit's coordinated
graphics code (``GLContext``, ``TextureMapper``, ``ThreadedCompositor``, Skia's
Ganesh backend) is nevertheless compiled into the port and calls the EGL and
OpenGL ES entry points, so the link needs them defined. Every function the
headers declare is defined here to do nothing and return zero, which is a
conforming "there is no display" implementation: ``eglGetDisplay`` returns
``EGL_NO_DISPLAY``, ``eglInitialize`` fails, ``eglGetError`` reports
``EGL_NOT_INITIALIZED``, ``eglGetProcAddress`` finds nothing and every GL call
is a no-op. A page that paints on the CPU never reaches them; one that tries
to (WebGL, accelerated compositing) finds no display and says so.

Reading the prototypes from the headers (instead of listing the functions
WebKit calls today) keeps the stub complete as WebKit's use of GL changes,
and the compiler checks each definition against the header it came from.

Usage: gen_stub.py INCLUDE_DIR OUT_DIR   (writes OUT_DIR/egl_stub.c and gles_stub.c)
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

#: Headers whose prototypes go to each library.
EGL_HEADERS = ["EGL/egl.h", "EGL/eglext.h"]
GLES_HEADERS = ["GLES2/gl2.h", "GLES2/gl2ext.h", "GLES3/gl3.h", "GLES3/gl31.h", "GLES3/gl32.h"]
#: Functions that must not return plain zero (0x3001 is EGL_NOT_INITIALIZED).
RETURNS = {"eglGetError": "0x3001"}
DECLARATION = re.compile(
    r"^(?:EGLAPI|GL_APICALL)\s+(.*?)\s*(?:EGLAPIENTRY|GL_APIENTRY)\s+(\w+)\s*\((.*?)\)\s*;",
    re.S | re.M)


def prototypes(headers: list[str], root: Path) -> dict[str, tuple[str, str]]:
    """``{name: (return type, parameter list)}`` of every function the headers declare."""
    found: dict[str, tuple[str, str]] = {}
    for header in headers:
        text = (root / header).read_text(encoding="utf-8", errors="replace")
        for match in DECLARATION.finditer(text):
            result, name, params = match.groups()
            found.setdefault(name, (" ".join(result.split()), " ".join(params.split())))
    return found


def definition(name: str, result: str, params: str) -> str:
    """One stub: void functions do nothing, the rest return zero (a null pointer too)."""
    body = "" if result == "void" else f"return {RETURNS.get(name, '0')};"
    return f"{result} {name}({params}) {{ {body} }}"


def write(path: Path, includes: list[str], protos: dict[str, tuple[str, str]]) -> None:
    lines = [f"/* Generated by gen_stub.py from the Khronos headers: {len(protos)} functions that do nothing. */",
             "#define EGL_EGLEXT_PROTOTYPES 1", "#define GL_GLEXT_PROTOTYPES 1"]
    lines += [f"#include <{header}>" for header in includes]
    lines.append("")
    lines += [definition(name, *protos[name]) for name in sorted(protos)]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    root, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    egl = prototypes(EGL_HEADERS, root)
    gles = prototypes(GLES_HEADERS, root)
    if len(egl) < 100 or len(gles) < 400:
        print(f"gen_stub: only {len(egl)} EGL and {len(gles)} GLES prototypes found in {root}",
              file=sys.stderr)
        return 1
    write(out / "egl_stub.c", EGL_HEADERS, egl)
    write(out / "gles_stub.c", GLES_HEADERS, gles)
    print(f"gen_stub: {len(egl)} EGL and {len(gles)} GLES functions", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
