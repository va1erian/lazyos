#!/usr/bin/env python3
"""The page `frame_run.py` scrolls: 600 text lines on alternating bands, no script, no animation.

WebKit's own `tall.html` is 40 bands (about 39 wheel notches of travel), too short to hold a
wheel turning for twenty seconds. This one is 24 000 CSS px tall and carries real text, so a
repaint costs what a text page costs rather than that of a few flat rectangles.

    python tools/webplus/scroll_page.py --write     # tools/web/fixtures/theoldnet.com/webplus/scroll.html
    python tools/webplus/scroll_page.py --check     # the committed file is current
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "tools" / "web" / "fixtures" / "theoldnet.com" / "webplus" / "scroll.html"
TITLE = "WebPlus scroll"
LINES = 600
LINE_PX = 40

WORDS = ("lazy operating system renders text in software on one core while the wheel turns and the "
         "compositor presents damage rectangles to a framebuffer that the monitor scans out").split()


def sentence(index: int) -> str:
    """A deterministic line of about 80 characters that differs from its neighbours."""
    words = [WORDS[(index * 7 + step * 3) % len(WORDS)] for step in range(12)]
    return " ".join(words)


def render() -> str:
    head = f"""<!doctype html>
<html>
<head>
<meta charset="utf-8">
<title>{TITLE}</title>
<style>
  /* Generated by tools/webplus/scroll_page.py: {LINES} lines of {LINE_PX} px, alternating shades, a
     little bold and a link-coloured word in each, so the page has text to rasterise. */
  body {{ margin: 0; font: 18px/{LINE_PX}px sans-serif; color: #202020; }}
  div {{ height: {LINE_PX}px; padding-left: 12px; white-space: nowrap; overflow: hidden; }}
  div:nth-child(2n) {{ background: #eef2f7; }}
  div:nth-child(5n) {{ background: #f7efe6; }}
  b {{ color: #0b5394; }}
</style>
</head>
<body>
"""
    rows = []
    for index in range(LINES):
        text = sentence(index)
        first, _, rest = text.partition(" ")
        rows.append(f"<div>{index + 1:03d} <b>{first}</b> {rest}</div>")
    return head + "\n".join(rows) + "\n</body>\n</html>\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.write:
        PAGE.parent.mkdir(parents=True, exist_ok=True)
        PAGE.write_bytes(render().encode("utf-8"))
        print(f"wrote {PAGE.relative_to(ROOT)}")
        return 0
    if args.check:
        current = PAGE.is_file() and PAGE.read_bytes() == render().encode("utf-8")
        print("scroll page current" if current else "scroll page is stale: run --write")
        return 0 if current else 1
    parser.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())
