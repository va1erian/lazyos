"""midlc Java backend: records and the wire codec.

Part of the Messenger IDL compiler; see `midlc_java.py`. Emits the Java
classes of structs, argument and reply records, and each interface's
`<Base>Codec`: the encode and decode of every struct and message over
LazyVM's `lazy.internal.msg.WireWriter`/`WireReader`, which write the same
bytes as `libmessenger` (held to `idl/conformance` by LazyVM's
`tests/java/lazy/msg/Conformance`).
"""

from __future__ import annotations

from midlc_java_names import SCALARS, Names, javadoc
from midlc_model import Method, Param, Type
from midlc_objects import object_kind

# The most parameters a method takes positionally; past it, an `<M>Args` record.
MAX_POSITIONAL = 4

HEADER = "// @generated by tools/midlc/midlc.py --java - do not edit.\n"
IMPORTS = """\
import java.util.concurrent.CompletionStage;
import lazy.internal.msg.*;
"""


class Temps:
    """Fresh local names for nested containers in one generated method."""

    def __init__(self):
        self.count = 0

    def next(self, prefix: str) -> str:
        self.count += 1
        return f"{prefix}{self.count}"


def java_file(names: Names, body: list[str]) -> str:
    return HEADER + f"package {names.package};\n\n" + IMPORTS + "\n" + "\n".join(body).rstrip() + "\n"


def write_lines(names: Names, ty: Type, fid: str, value: str, label: str, pad: str, temps: Temps) -> list[str]:
    """Statements writing `value` of type `ty` as field `fid` of the writer `w`."""
    kind = object_kind(ty)
    need = f'Wire.need({value}, "{label}")'
    if kind == "channel":
        return [f"{pad}w.handle({fid}, Listeners.local({need}, {names.codec_of(ty.args[0].name)}::deliver));"]
    if kind == "buffer":
        return [f"{pad}w.buffer({fid}, {value});"]
    if ty.enum or ty.name in names.enums:
        return [f"{pad}w.variant({fid}, {need});"]
    if ty.name in SCALARS:
        return [f"{pad}w.{SCALARS[ty.name][3]}({fid}, {value});"]
    if ty.name == "String":
        return [f"{pad}w.string({fid}, {need});"]
    if ty.name == "Bytes":
        return [f"{pad}w.bytes({fid}, {need});"]
    mark = temps.next("m")
    if ty.name == "Array":
        item = temps.next("x")
        inner = ty.args[0]
        item_value = f'Wire.need({item}, "{label}[]")' if inner.name in SCALARS else item
        return [
            f"{pad}int {mark} = w.begin(Wire.ARRAY, {fid});",
            f"{pad}for ({names.java_type(inner, True)} {item} : {need}) {{",
            *write_lines(names, inner, "1", item_value, f"{label}[]", pad + "    ", temps),
            f"{pad}}}",
            f"{pad}w.end({mark});",
        ]
    if ty.name == "Option":
        some = temps.next("o")
        return [
            f"{pad}int {mark} = w.begin(Wire.OPTION, {fid});",
            f"{pad}{names.java_type(ty, True)} {some} = {value};",
            f"{pad}if ({some} != null) {{",
            *write_lines(names, ty.args[0], "1", some, label, pad + "    ", temps),
            f"{pad}}}",
            f"{pad}w.end({mark});",
        ]
    return [
        f"{pad}int {mark} = w.begin(Wire.STRUCT, {fid});",
        f"{pad}{names.codec}.write{ty.name}(w, {need});",
        f"{pad}w.end({mark});",
    ]


def read_expr(names: Names, ty: Type, reader: str, depth: int = 0) -> str:
    """An expression reading the current field of `reader` as `ty`."""
    kind = object_kind(ty)
    if kind == "channel":
        return f"{reader}.handle({names.codec_of(ty.args[0].name)}::remote)"
    if kind == "buffer":
        return f"{reader}.buffer()"
    if ty.enum or ty.name in names.enums:
        return f'{reader}.variant({ty.name}.values(), "{ty.name}")'
    if ty.name in SCALARS:
        return f"{reader}.{SCALARS[ty.name][3]}()"
    if ty.name == "String":
        return f"{reader}.string()"
    if ty.name == "Bytes":
        return f"{reader}.bytes()"
    item = f"e{depth + 1}"
    if ty.name == "Array":
        return f"{reader}.list({item} -> {read_expr(names, ty.args[0], item, depth + 1)})"
    if ty.name == "Option":
        return f"{reader}.option({item} -> {read_expr(names, ty.args[0], item, depth + 1)})"
    return f"{names.codec}.read{ty.name}({reader}.open(Wire.STRUCT))"


def decode_loop(names: Names, fields: list[Param], target: str, pad: str) -> list[str]:
    """Reads the fields of reader `r` into `target + name`; unknown ids are skipped."""
    lines = [f"{pad}while (r.next()) {{", f"{pad}    switch (r.id()) {{"]
    for f in fields:
        lines.append(f"{pad}        case {f.id}: {target}{names.field(f)} = {read_expr(names, f.ty, 'r')}; break;")
    lines += [f"{pad}        default: break;", f"{pad}    }}", f"{pad}}}"]
    return lines


def emit_record(names: Names, name: str, fields: list[Param], doc: str) -> str:
    """A struct, or an `<M>Args`/`<M>Reply` record: public fields with their
    zero values, fluent setters, `equals`, `hashCode` and `toString`."""
    body = javadoc(doc, "") + [f"public final class {name} {{"]
    for f in fields:
        body.append(f"    public {names.java_type(f.ty)} {names.field(f)} = {names.zero(f.ty)};")
    body += ["", f"    public {name}() {{}}", ""]
    for f in fields:
        fname = names.field(f)
        body += [
            f"    public {name} {names.setter(f)}({names.java_type(f.ty)} {fname}) {{",
            f"        this.{fname} = {fname};",
            "        return this;",
            "    }",
            "",
        ]
    body += record_methods(names, name, fields)
    body.append("}")
    return java_file(names, body)


def record_methods(names: Names, name: str, fields: list[Param]) -> list[str]:
    def same(f: Param) -> str:
        n = names.field(f)
        jt = names.java_type(f.ty)
        if jt == "byte[]":
            return f"java.util.Arrays.equals(this.{n}, o.{n})"
        if jt == "double":
            return f"Double.compare(this.{n}, o.{n}) == 0"
        if jt in ("boolean", "int", "long"):
            return f"this.{n} == o.{n}"
        return f"java.util.Objects.equals(this.{n}, o.{n})"

    def hashed(f: Param) -> str:
        n = names.field(f)
        return f"java.util.Arrays.hashCode(this.{n})" if names.java_type(f.ty) == "byte[]" else f"this.{n}"

    def shown(f: Param) -> str:
        n = names.field(f)
        return f"java.util.Arrays.toString(this.{n})" if names.java_type(f.ty) == "byte[]" else f"this.{n}"

    equal = " && ".join(same(f) for f in fields) or "true"
    hashes = ", ".join(hashed(f) for f in fields)
    text = ' + ", " + '.join(f'"{names.field(f)}=" + {shown(f)}' for f in fields) or '""'
    return [
        "    @Override",
        "    public boolean equals(Object other) {",
        "        if (this == other) return true;",
        f"        if (!(other instanceof {name})) return false;",
        f"        {name} o = ({name}) other;",
        f"        return {equal};",
        "    }",
        "",
        "    @Override",
        "    public int hashCode() {",
        f"        return java.util.Objects.hash({hashes});",
        "    }",
        "",
        "    @Override",
        "    public String toString() {",
        f'        return "{name}[" + {text} + "]";',
        "    }",
    ]


def positional(method: Method) -> bool:
    return len(method.params) <= MAX_POSITIONAL


def param_list(names: Names, method: Method) -> str:
    """The Java parameters a method takes: positional, or its `<M>Args`."""
    if not positional(method):
        return f"{method.name}Args args"
    return ", ".join(f"{names.java_type(p.ty)} {names.param(p)}" for p in method.params)


def arg_names(names: Names, method: Method) -> str:
    return "args" if not positional(method) else ", ".join(names.param(p) for p in method.params)


def reply_type(names: Names, method: Method) -> str:
    """What a call's stage holds: `Void`, its one field (boxed), or `<M>Reply`."""
    if method.oneway or not method.returns:
        return "Void"
    if len(method.returns) == 1:
        return names.java_type(method.returns[0].ty, True)
    return f"{method.name}Reply"


def decoded_args(names: Names, method: Method, source: str) -> str:
    """The Java arguments of a call to the method, from `Object[] a` or the `<M>Args`."""
    if not positional(method):
        return source
    return ", ".join(f"({names.java_type(p.ty, True)}) a[{i}]" for i, p in enumerate(method.params))


def message_codecs(names: Names, method: Method) -> list[str]:
    """`write<M>Args`, `read<M>Args` and, for a call, `write<M>Reply`/`read<M>Reply`."""
    temps = Temps()
    if positional(method):
        out = [f"    public static void write{method.name}Args(WireWriter w, {param_list(names, method)}) {{".replace("WireWriter w, )", "WireWriter w)")]
        for p in method.params:
            out += write_lines(names, p.ty, str(p.id), names.param(p), p.name, "        ", temps)
        out += ["    }", ""]
        out.append(f"    public static Object[] read{method.name}Args(WireReader r) {{")
        out.append("        Object[] a = {" + ", ".join(names.zero(p.ty) for p in method.params) + "};")
        out.append("        while (r.next()) {")
        out.append("            switch (r.id()) {")
        for i, p in enumerate(method.params):
            out.append(f"                case {p.id}: a[{i}] = {read_expr(names, p.ty, 'r')}; break;")
        out += ["                default: break;", "            }", "        }", "        return a;", "    }", ""]
    else:
        out = record_codec(names, f"{method.name}Args", f"{method.name}Args", method.params)
    if method.oneway:
        return out
    if len(method.returns) > 1:
        return out + record_codec(names, f"{method.name}Reply", f"{method.name}Reply", method.returns)
    rtype = reply_type(names, method)
    temps = Temps()
    out.append(f"    public static void write{method.name}Reply(WireWriter w, {rtype} v) {{")
    if len(method.returns) == 1:
        f = method.returns[0]
        out += write_lines(names, f.ty, str(f.id), "v", f.name, "        ", temps)
    out += ["    }", "", f"    public static {rtype} read{method.name}Reply(WireReader r) {{"]
    if not method.returns:
        out.append("        return null;")
    elif len(method.returns) == 1:
        f = method.returns[0]
        out.append(f"        {names.java_type(f.ty, True)} v = {names.zero(f.ty)};")
        out += [
            "        while (r.next()) {",
            f"            if (r.id() == {f.id}) v = {read_expr(names, f.ty, 'r')};",
            "        }",
            "        return v;",
        ]
    out += ["    }", ""]
    return out


def record_codec(names: Names, suffix: str, cls: str, fields: list[Param]) -> list[str]:
    """`write<suffix>` and `read<suffix>` for a record class `cls`."""
    temps = Temps()
    out = [f"    public static void write{suffix}(WireWriter w, {cls} v) {{", f'        Wire.need(v, "{cls}");']
    for f in fields:
        out += write_lines(names, f.ty, str(f.id), f"v.{names.field(f)}", f.name, "        ", temps)
    out += ["    }", "", f"    public static {cls} read{suffix}(WireReader r) {{", f"        {cls} v = new {cls}();"]
    out += decode_loop(names, fields, "v.", "        ")
    out += ["        return v;", "    }", ""]
    return out
