"""midlc conformance, Java side: hold the generated Java codecs to the corpus.

Part of the Messenger IDL compiler; see `midlc_conformance.py`. For every
valid corpus case it emits the classes `midlc_java` generates and one Java
test (LazyVM's `tests/java/lazy/msg/Conformance`) that encodes each sample
value with them, compares the bytes with those the independent `midlc_wire`
encoder writes, then decodes the corpus bytes and encodes the result again.
Standard-error samples go through LazyVM's `WireWriter.error` and
`WireReader.fault`. A sample that carries kernel objects is skipped and
counted: the Java runtime gives objects their meaning only with a transport.
"""

from __future__ import annotations

import json
import struct
from pathlib import Path

from midlc_conformance import ERROR_MESSAGE, encode_vector, parse_case
from midlc_java import generate_java
from midlc_java_codec import positional
from midlc_java_names import SCALARS, Names, constant, java_string
from midlc_model import Interface, Method, MidlError, Param, Type
from midlc_wire import message_objects

HEADER = """\
// @generated by tools/midlc/conformance_java.py - do not edit.
// The midlc Java codecs held to the bytes idl/conformance records for each sample
// value (LazyOS docs/midl.md, "Conformance corpus"). Prints one line per sample.
package {package};

import java.util.Arrays;
import java.util.function.Consumer;
import java.util.function.Function;
import lazy.internal.msg.Fault;
import lazy.internal.msg.WireReader;
import lazy.internal.msg.WireWriter;

public class {name} {{
    private static int failed;

    public static void main(String[] args) {{
"""

FOOTER = """\
        System.out.println(failed == 0 ? "conformance: PASS" : "conformance: " + failed + " FAILED");
    }

    private static void check(String name, String hex, Consumer<WireWriter> encode, Function<WireReader, byte[]> again) {
        byte[] want = bytes(hex);
        WireWriter w = new WireWriter();
        encode.accept(w);
        byte[] got = w.toBytes();
        byte[] round = again.apply(new WireReader(want));
        boolean ok = Arrays.equals(want, got) && Arrays.equals(want, round);
        if (!ok) failed++;
        System.out.println((ok ? "PASS " : "FAIL ") + name);
    }

    private static void skip(String name, String why) {
        System.out.println("SKIP " + name + ": " + why);
    }

    private static byte[] bytes(String hex) {
        byte[] out = new byte[hex.length() / 2];
        for (int i = 0; i < out.length; i++) out[i] = (byte) Integer.parseInt(hex.substring(2 * i, 2 * i + 2), 16);
        return out;
    }
}
"""


def emit_conformance_java(corpus: Path, package: str, name: str) -> tuple[str, dict[str, str]]:
    """The test source and the generated classes (`{relative path: text}`) it uses."""
    lines: list[str] = []
    classes: dict[str, str] = {}
    for midl in sorted((corpus / "valid").glob("*.midl")):
        interfaces, _ = parse_case(midl.read_text(encoding="utf-8"))
        classes.update(generate_java(interfaces))
        by_name = {i.name: i for i in interfaces}
        vectors_path = midl.with_suffix(".vectors.json")
        vectors = json.loads(vectors_path.read_text(encoding="utf-8")) if vectors_path.is_file() else []
        for vector in vectors:
            label = f"{midl.stem}/{vector['name']}"
            body, _ = encode_vector(interfaces, vector)
            lines += vector_lines(by_name, interfaces[0], vector, label, body.hex())
    source = HEADER.format(package=package, name=name) + "\n".join(lines) + "\n" + FOOTER
    return source, classes


def vector_lines(by_name: dict[str, Interface], first: Interface, vector: dict, label: str, hex_bytes: str) -> list[str]:
    pad = "        "
    message, value = vector["message"], vector["value"]
    if message == ERROR_MESSAGE:
        domain = java_string(value.get("domain", ""))
        hint = java_string(value["hint"]) if value.get("hint") is not None else "null"
        docs = java_string(value["docs"]) if value.get("docs") is not None else "null"
        return [
            f"{pad}check({java_string(label)}, {java_string(hex_bytes)},",
            f"{pad}        w -> w.error({value['code']}, {java_string(value['message'])}, {domain}, {hint}, {docs}),",
            f"{pad}        r -> WireReader.fault(bytes({java_string(hex_bytes)})).body());",
        ]
    interface = by_name[vector.get("interface", first.name)]
    names = Names(interface, by_name)
    codec = f"{names.package}.{names.codec}"
    if message_objects(interface, message):
        return [f'{pad}skip({java_string(label)}, "carries kernel objects");']
    if "." not in message:
        record = next(s for s in interface.structs if s.name == message)
        lit = record_literal(names, f"{names.package}.{message}", record.fields, value)
        return check_lines(pad, label, hex_bytes, f"{codec}.write{message}(w, {lit})",
                           f"{codec}.write{message}(w2, {codec}.read{message}(r))")
    method_name, kind = message.split(".", 1)
    method = next(m for m in interface.methods if m.name == method_name)
    if kind == "args":
        return args_lines(names, codec, method, value, pad, label, hex_bytes)
    return reply_lines(names, codec, method, value, pad, label, hex_bytes)


def check_lines(pad: str, label: str, hex_bytes: str, encode: str, again: str) -> list[str]:
    return [
        f"{pad}check({java_string(label)}, {java_string(hex_bytes)},",
        f"{pad}        w -> {encode},",
        f"{pad}        r -> {{ WireWriter w2 = new WireWriter(); {again}; return w2.toBytes(); }});",
    ]


def args_lines(names: Names, codec: str, method: Method, value: dict, pad: str, label: str, hex_bytes: str) -> list[str]:
    if not positional(method):
        lit = record_literal(names, f"{names.package}.{method.name}Args", method.params, value)
        return check_lines(pad, label, hex_bytes, f"{codec}.write{method.name}Args(w, {lit})",
                           f"{codec}.write{method.name}Args(w2, {codec}.read{method.name}Args(r))")
    lits = "".join(f", {literal(names, p.ty, value[p.name])}" for p in method.params)
    casts = "".join(
        f", ({qualified(names, p.ty, True)}) a[{i}]" for i, p in enumerate(method.params))
    return check_lines(pad, label, hex_bytes, f"{codec}.write{method.name}Args(w{lits})",
                       f"Object[] a = {codec}.read{method.name}Args(r); {codec}.write{method.name}Args(w2{casts})")


def reply_lines(names: Names, codec: str, method: Method, value: dict, pad: str, label: str, hex_bytes: str) -> list[str]:
    if len(method.returns) > 1:
        lit = record_literal(names, f"{names.package}.{method.name}Reply", method.returns, value)
    elif method.returns:
        lit = literal(names, method.returns[0].ty, value[method.returns[0].name])
    else:
        lit = "null"
    return check_lines(pad, label, hex_bytes, f"{codec}.write{method.name}Reply(w, {lit})",
                       f"{codec}.write{method.name}Reply(w2, {codec}.read{method.name}Reply(r))")


def qualified(names: Names, ty: Type, boxed: bool = False) -> str:
    """The Java type, with the interface's own types written in full."""
    if ty.name == "Array":
        return f"java.util.List<{qualified(names, ty.args[0], True)}>"
    if ty.name == "Option":
        return qualified(names, ty.args[0], True)
    if ty.enum or ty.name in names.enums or ty.name in names.structs:
        return f"{names.package}.{ty.name}"
    return names.java_type(ty, boxed)


def record_literal(names: Names, cls: str, fields: list[Param], value: dict) -> str:
    setters = "".join(f".{names.setter(f)}({literal(names, f.ty, value[f.name])})" for f in fields)
    return f"new {cls}(){setters}"


def literal(names: Names, ty: Type, value) -> str:
    """`value` as a Java expression of the generated type of `ty`."""
    if ty.enum or ty.name in names.enums:
        variants = next(e.variants for e in names.interface.enums if e.name == ty.name)
        variant = variants[value] if isinstance(value, int) else value
        return f"{names.package}.{ty.name}.{constant(variant)}"
    if ty.name == "Bool":
        return "true" if value else "false"
    if ty.name == "I32":
        return str(value)
    if ty.name in ("I64", "U32", "U64"):
        return f"0x{value & 0xFFFFFFFFFFFFFFFF:x}L"
    if ty.name == "F64":
        return f"Double.longBitsToDouble(0x{struct.unpack('<Q', struct.pack('<d', value))[0]:x}L)"
    if ty.name == "String":
        return java_string(value)
    if ty.name == "Bytes":
        return f"bytes({java_string(value)})"
    if ty.name == "Array":
        inner = ty.args[0]
        items = ", ".join(boxed_literal(names, inner, v) for v in value)
        return f"Arrays.<{qualified(names, inner, True)}>asList({items})"
    if ty.name == "Option":
        return "null" if value is None else boxed_literal(names, ty.args[0], value)
    record = next((s for s in names.interface.structs if s.name == ty.name), None)
    if record is None:
        raise MidlError(f"no Java literal for {ty}")
    return record_literal(names, f"{names.package}.{ty.name}", record.fields, value)


def boxed_literal(names: Names, ty: Type, value) -> str:
    """A literal where a box is expected: an `int` literal is no `Long`."""
    text = literal(names, ty, value)
    if ty.name in SCALARS and not ty.enum:
        return f"({SCALARS[ty.name][0]}) {text}"
    return text
