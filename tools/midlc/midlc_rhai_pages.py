"""midlc Rhai API backend: the reference pages the Docs app shows (`docs/rhai/api/`).

Part of the Messenger IDL compiler; the modules themselves come from
`midlc_rhai`, and `midlc_rhai_docs` writes the one-page summary next to them.
This backend writes what a script author reads on the guest: an index and one
page per `sys::<alias>` module (every function with its arguments, replies
and documentation, the structs, enums and topics), linked to the wire-level
page of the same interface in `docs/idl/`.

Output (`--rhai-docs DIR`): `DIR/index.md` and `DIR/<alias>.md`.
"""

from __future__ import annotations

from midlc_model import Interface, Method, Param, Struct, Type, snake_case
from midlc_rhai import (
    alias,
    callable_methods,
    param_name,
    placeholder_names,
    scriptable,
    signature,
    topic_helpers,
)

#: Where the wire-level pages (`midlc --docs`) sit, relative to a page here.
WIRE_DIR = "../../idl"

INDEX_INTRO = """\
# Messenger APIs for Rhai (`sys::*`)

Every Messenger interface in `idl/` is a Rhai module under `sys::`, generated by
`midlc --rhai-api`. The modules exist in the `rhai` command and in every LazyRAD
form script on LazyOS. This is the reference: one page per module, listing each
function with its arguments, reply, errors and the documentation written in the
interface's `.midl` file.

```rhai
let theme = sys::confd::get("sys/ui/theme");          // call a method
let value = sys::confd::new_value();                  // build a struct
sys::confd::on_changed("sys/ui/#", |event| {          // react to a topic
    print(event.payload.path);
});
```

## Conventions

| What | Rule |
|---|---|
| Function names | the IDL method name in snake_case: `GetMaster` is `get_master()` |
| Arguments | positional, in the IDL order; a name that is a Rhai keyword gets a trailing `_` |
| Reply | the value for one reply field, a map for several, `()` for none |
| Structs | object maps; `new_<struct>()` returns one with every field at its zero value; unknown keys are an error |
| Enums | the variant name as a string; `<ENUM>` is the list and `<ENUM>_<VARIANT>` each constant |
| `Option<T>` | `()` for none, otherwise the value |
| Failure | a catchable error carrying the service's own text and the errno name |
| Topics | per topic: `<NAME>_PATTERN`, `<name>_topic(..)`, `on_<name>(.., handler)`, `subscribe_<name>(..)`, `publish_<name>(.., payload)` |

How values, errors, timeouts and events work is in [msg](../msg.md); worked
examples are in the [Rhai cookbook](../cookbook.md). Kernel ACL scopes (interfaces
no service receives) have no module, and a method whose request carries a
channel, buffer or ring cannot be called from a script and is listed as such.

## Modules

| Module | Interface | About | Wire reference |
|---|---|---|---|
"""


def first_sentence(text: str) -> str:
    """The first line of `text`, trimmed of a trailing colon or semicolon."""
    line = text.strip().splitlines()[0] if text.strip() else ""
    return line.replace("|", "/")


def rhai_type(ty: Type) -> str:
    """How a value of IDL type `ty` reads and is written in a script."""
    if ty.name == "Bool":
        return "bool"
    if ty.name in ("I32", "U32", "I64", "U64"):
        return "int"
    if ty.name == "F64":
        return "float"
    if ty.name == "String":
        return "string"
    if ty.name == "Bytes":
        return "blob"
    if ty.name == "Array":
        return f"array of {rhai_type(ty.args[0])}"
    if ty.name == "Option":
        return f"{rhai_type(ty.args[0])} or ()"
    if ty.enum:
        return f"string (`{ty.name}` variant)"
    return f"map (`{ty.name}`)"


def param_rows(params: list[Param]) -> list[str]:
    rows = ["| Name | IDL type | Script value |", "|---|---|---|"]
    rows += [f"| `{param_name(p.name)}` | `{p.ty}` | {rhai_type(p.ty)} |" for p in params]
    return rows


def method_section(interface: Interface, method: Method) -> list[str]:
    name = alias(interface)
    fn = snake_case(method.name)
    args = ", ".join(param_name(p.name) for p in method.params)
    lines = [f"### `{fn}({args})`", "", f"`{signature(method)}`", ""]
    if method.doc:
        lines += [method.doc, ""]
    if method.params:
        lines += ["Arguments:", ""] + param_rows(method.params) + [""]
    if method.oneway:
        lines += ["One-way: the call returns `()` once the message is queued.", ""]
    elif not method.returns:
        lines += ["Returns `()`.", ""]
    elif len(method.returns) == 1:
        reply = method.returns[0]
        lines += [f"Returns `{reply.name}`: `{reply.ty}` ({rhai_type(reply.ty)}).", ""]
    else:
        lines += ["Returns a map:", ""] + param_rows(method.returns) + [""]
    lines += ["```rhai", f"let result = sys::{name}::{fn}({args});", "```", ""]
    return lines


def struct_section(struct: Struct) -> list[str]:
    lines = [f"### `{struct.name}`", ""]
    if struct.doc:
        lines += [struct.doc, ""]
    lines += param_rows(struct.fields) + [""]
    lines += ["```rhai", f"let value = sys::MODULE::new_{snake_case(struct.name)}();", "```", ""]
    return lines


def topic_section(interface: Interface) -> list[str]:
    helpers = topic_helpers(interface)
    if not helpers:
        return []
    lines = ["## Topics", ""]
    for topic, stem in helpers:
        names = placeholder_names(topic)
        lead = ", ".join(names + ["handler"])
        calls = [f"`{stem.upper()}_PATTERN`"]
        if names:
            calls.append(f"`{stem}_topic({', '.join(names)})`")
        calls += [
            f"`on_{stem}({lead})`",
            f"`subscribe_{stem}({', '.join(names)})`",
            f"`publish_{stem}({', '.join(names + ['payload'])})`",
        ]
        lines += [f"### `{topic.source}`", ""]
        if topic.doc:
            lines += [topic.doc, ""]
        lines += [
            f"Payload `{topic.payload}`, QoS `{topic.qos}`"
            + (", retained." if topic.retained else "."),
            "",
            "Helpers: " + ", ".join(calls) + ".",
            "",
            "```rhai",
            f"sys::{alias(interface)}::on_{stem}({lead.replace('handler', '|event| print(event.payload)')});",
            "```",
            "",
        ]
    return lines


def module_page(interface: Interface) -> str:
    name = alias(interface)
    lines = [
        f"# `sys::{name}`",
        "",
        f"The Rhai module for the Messenger interface `{interface.name}`. "
        f"Wire-level reference: [{interface.name}]({WIRE_DIR}/{interface.name}.md).",
        "",
    ]
    if interface.docs:
        lines += [interface.docs, ""]
    methods = callable_methods(interface)
    if methods:
        lines += ["## Functions", ""]
        for method in methods:
            lines += method_section(interface, method)
    skipped = [m.name for m in interface.methods if m.objects]
    if skipped:
        lines += [
            "Not callable from a script (the request carries a kernel object): "
            + ", ".join(f"`{m}`" for m in skipped) + ".",
            "",
        ]
    if interface.structs or interface.enums:
        lines += ["## Types", ""]
        for struct in interface.structs:
            lines += [line.replace("sys::MODULE", f"sys::{name}") for line in struct_section(struct)]
        for enum in interface.enums:
            prefix = snake_case(enum.name).upper()
            lines += [f"### `{enum.name}`", "", "A string; the constants of this module are:", ""]
            lines += [f"- `{prefix}_{snake_case(v).upper()}` = `\"{v}\"`" for v in enum.variants]
            lines += ["", f"`{prefix}` is the array of all of them.", ""]
    lines += topic_section(interface)
    lines += [
        "## See also",
        "",
        "- [Messenger APIs for Rhai](index.md)",
        "- [msg: Messenger from Rhai](../msg.md)",
        f"- [{interface.name} on the wire]({WIRE_DIR}/{interface.name}.md)",
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


def index_page(interfaces: list[Interface]) -> str:
    lines = [INDEX_INTRO.rstrip("\n")]
    for interface in interfaces:
        name = alias(interface)
        about = first_sentence(interface.docs)
        lines.append(
            f"| [`sys::{name}`]({name}.md) | `{interface.name}` | {about} "
            f"| [wire]({WIRE_DIR}/{interface.name}.md) |"
        )
    lines += ["", "## See also", "", "- [msg: Messenger from Rhai](../msg.md)",
              "- [Rhai cookbook](../cookbook.md)", "- [Messenger](../../messenger.md)",
              "- [MIDL, the interface language](../../midl.md)"]
    return "\n".join(lines) + "\n"


def emit_rhai_pages(interfaces: list[Interface]) -> dict[str, str]:
    """Every file of the `--rhai-docs` directory, by file name."""
    chosen = scriptable(interfaces)
    files = {f"{alias(i)}.md": module_page(i) for i in chosen}
    files["index.md"] = index_page(chosen)
    return files
