#!/usr/bin/env python3
"""midlc - the Messenger IDL compiler (issue #90).

Reads `.midl` interface definitions (docs/messenger.md section 11) and emits:

  * Rust wire helpers (encode/decode over the `libmessenger` parcel codec),
  * a Markdown reference per interface (signatures, types),
  * a machine-readable manifest (method ids and the interface hash),
  * a schema table (`--schema`): every interface as static data for dynamic
    clients such as the Rhai `msg` module (`midlc_schema`),
  * Rhai API modules (`--rhai-api DIR`): one `sys::<alias>` module per
    interface, their Rust index and reference page (`midlc_rhai`),
  * Rhai API reference pages for the Docs app (`--rhai-docs DIR`: an index and
    one page per module, `midlc_rhai_pages`).

Usage:
    python tools/midlc/midlc.py --out libs/generated/src/lib.rs idl/echo.midl
    python tools/midlc/midlc.py --check --out libs/generated/src/lib.rs idl/echo.midl
    python tools/midlc/midlc.py --manifest build/manifest.json idl/echo.midl
    python tools/midlc/midlc.py --schema libs/rhai-lazy/src/msg/idl.rs idl/*.midl
    python tools/midlc/midlc.py --rhai-api libs/rhai-lazy/api idl/*.midl
    python tools/midlc/midlc.py --rhai-docs docs/rhai/api idl/*.midl

`--check` regenerates in memory and fails if the committed `--out` (and, when
given, `--schema`, `--rhai-api` or `--rhai-docs`) output differs, so
generated code cannot silently drift; CI runs it on every pull request.

`--out` writes the crate's root file and, beside it, one file per interface and
per shared module (`midlc_split`); the `[features]` block of the crate's
`Cargo.toml` is rewritten between its markers.

Grammar (small on purpose):

    interface os.lazy.echo.v1 {
        /// Doc comment for the method.
        method Echo(text: String, count: U32) -> (reply: String);
        method Notify(event: Event) -> () oneway;    // oneway methods return ()
        method Watch(id: U64, events: Channel<os.lazy.echo.v1>) -> ();
        struct Event { topic: String, at: U64 }
        enum Level { Info, Warn, Error }
    }

Beside methods, an interface may declare `errors { NotFound = 1001 }`, and a
file `service "os.lazy.echo" implements os.lazy.echo.v1;`; a method takes the
attributes `scope "os.lazy.x.v1"` and `deadline=500ms` (`midlc_decls`).

`Channel<interface>`, `Buffer` and `Ring<...>` are the kernel objects a request
carries (its parcel's object list); they are parameter types, legal in a
request and inside a struct, never in a reply, a topic, an `Option` or an
`Array`; see `midlc_objects` and docs/midl.md.

Method ids are stable: an explicit `= 7` wins, otherwise a deterministic hash of
the method name is used; adding methods never renumbers existing ones.

The compiler is split across sibling modules so each stays small:
`midlc_model` (types and hashing), `midlc_lexer`, `midlc_parser`,
`midlc_rust` (Rust backend), `midlc_docs` (Markdown/manifest), and this CLI
entry point. Their public names are re-exported here for compatibility.
"""

