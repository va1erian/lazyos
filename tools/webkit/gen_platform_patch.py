#!/usr/bin/env python3
"""Regenerate ``webkit/patches/0003-platform-lazyos.patch``.

The PlayStation port's WebCore and WebKit sources pick their code by
``PLATFORM(PLAYSTATION)``. The LazyOS port reuses those sources, but WTF,
JavaScriptCore and bmalloc also test that macro (allocator, assertion, file
system and VM-tag code written for a console's libc) and must stay what the
proven JSCOnly build is; so the macro the port defines is ``PLATFORM(LAZYOS)``
and this patch renames every test of ``PLATFORM(PLAYSTATION)`` in
``Source/WebCore`` and ``Source/WebKit`` to it (mechanical: a word-for-word
replace, nothing else).

Usage: gen_platform_patch.py TREE   (TREE: an unpacked WebKitGTK 2.54.1 source tree;
the patch is written to webkit/patches/0003-platform-lazyos.patch)
"""

from __future__ import annotations

import difflib
import sys
from pathlib import Path

OLD, NEW = b"PLATFORM(PLAYSTATION)", b"PLATFORM(LAZYOS)"
ROOTS = ["Source/WebCore", "Source/WebKit"]
OUT = Path(__file__).resolve().parents[2] / "webkit" / "patches" / "0003-platform-lazyos.patch"
HEADER = """\
Rename PLATFORM(PLAYSTATION) to PLATFORM(LAZYOS) in WebCore and WebKit.

The LazyOS port is the PlayStation port's WebCore and WebKit code on Linux.
WTF, JavaScriptCore and bmalloc test PLATFORM(PLAYSTATION) too, for code that
is wrong on Linux, so the port defines its own platform macro
(WTF_PLATFORM_LAZYOS, Source/cmake/OptionsLazyOS.cmake) and only these two
projects, whose PlayStation code it wants, are renamed. Generated by
tools/webkit/gen_platform_patch.py; do not edit by hand.

"""


def files(tree: Path) -> list[Path]:
    found = []
    for root in ROOTS:
        for path in sorted((tree / root).rglob("*")):
            if path.is_file() and path.suffix in {".h", ".cpp", ".mm", ".c", ".txt", ".in", ".cmake"}:
                if OLD in path.read_bytes():
                    found.append(path)
    return found


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    tree = Path(sys.argv[1])
    chunks = [HEADER]
    count = 0
    for path in files(tree):
        old = path.read_bytes().decode("utf-8")
        new = old.replace(OLD.decode(), NEW.decode())
        name = path.relative_to(tree).as_posix()
        diff = difflib.unified_diff(old.splitlines(keepends=True), new.splitlines(keepends=True),
                                    f"a/{name}", f"b/{name}", n=3)
        chunks.append("".join(diff))
        count += old.count(OLD.decode())
    OUT.write_text("".join(chunks), encoding="utf-8", newline="\n")
    print(f"{count} replacements in {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
