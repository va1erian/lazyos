//! The arms of each box-drawing character, from the Unicode block's layout.

/// Stroke weights of the four arms: 0 none, 1 light, 2 heavy, 3 double.
#[derive(Clone, Copy)]
pub(crate) struct Arms {
    pub(crate) left: u8,
    pub(crate) right: u8,
    pub(crate) up: u8,
    pub(crate) down: u8,
}

const fn arms(left: u8, right: u8, up: u8, down: u8) -> Arms {
    Arms {
        left,
        right,
        up,
        down,
    }
}

/// The arms of box-drawing character `c` (`None` for the diagonals).
pub(crate) fn arms_of(c: char) -> Option<Arms> {
    let offset = (c as u32).checked_sub(0x2500)?;
    Some(match offset {
        0x00 | 0x04 | 0x08 | 0x4c => arms(1, 1, 0, 0),
        0x01 | 0x05 | 0x09 | 0x4d => arms(2, 2, 0, 0),
        0x02 | 0x06 | 0x0a | 0x4e => arms(0, 0, 1, 1),
        0x03 | 0x07 | 0x0b | 0x4f => arms(0, 0, 2, 2),
        // Corners, tees and crosses, light and heavy (U+250C..U+254B), in the
        // order the standard lists them.
        0x0c => arms(0, 1, 0, 1),
        0x0d => arms(0, 2, 0, 1),
        0x0e => arms(0, 1, 0, 2),
        0x0f => arms(0, 2, 0, 2),
        0x10 => arms(1, 0, 0, 1),
        0x11 => arms(2, 0, 0, 1),
        0x12 => arms(1, 0, 0, 2),
        0x13 => arms(2, 0, 0, 2),
        0x14 => arms(0, 1, 1, 0),
        0x15 => arms(0, 2, 1, 0),
        0x16 => arms(0, 1, 2, 0),
        0x17 => arms(0, 2, 2, 0),
        0x18 => arms(1, 0, 1, 0),
        0x19 => arms(2, 0, 1, 0),
        0x1a => arms(1, 0, 2, 0),
        0x1b => arms(2, 0, 2, 0),
        0x1c => arms(0, 1, 1, 1),
        0x1d => arms(0, 2, 1, 1),
        0x1e => arms(0, 1, 2, 1),
        0x1f => arms(0, 1, 1, 2),
        0x20 => arms(0, 1, 2, 2),
        0x21 => arms(0, 2, 2, 1),
        0x22 => arms(0, 2, 1, 2),
        0x23 => arms(0, 2, 2, 2),
        0x24 => arms(1, 0, 1, 1),
        0x25 => arms(2, 0, 1, 1),
        0x26 => arms(1, 0, 2, 1),
        0x27 => arms(1, 0, 1, 2),
        0x28 => arms(1, 0, 2, 2),
        0x29 => arms(2, 0, 2, 1),
        0x2a => arms(2, 0, 1, 2),
        0x2b => arms(2, 0, 2, 2),
        0x2c => arms(1, 1, 0, 1),
        0x2d => arms(2, 1, 0, 1),
        0x2e => arms(1, 2, 0, 1),
        0x2f => arms(2, 2, 0, 1),
        0x30 => arms(1, 1, 0, 2),
        0x31 => arms(2, 1, 0, 2),
        0x32 => arms(1, 2, 0, 2),
        0x33 => arms(2, 2, 0, 2),
        0x34 => arms(1, 1, 1, 0),
        0x35 => arms(2, 1, 1, 0),
        0x36 => arms(1, 2, 1, 0),
        0x37 => arms(2, 2, 1, 0),
        0x38 => arms(1, 1, 2, 0),
        0x39 => arms(2, 1, 2, 0),
        0x3a => arms(1, 2, 2, 0),
        0x3b => arms(2, 2, 2, 0),
        0x3c => arms(1, 1, 1, 1),
        0x3d => arms(2, 1, 1, 1),
        0x3e => arms(1, 2, 1, 1),
        0x3f => arms(2, 2, 1, 1),
        0x40 => arms(1, 1, 2, 1),
        0x41 => arms(1, 1, 1, 2),
        0x42 => arms(1, 1, 2, 2),
        0x43 => arms(2, 1, 2, 1),
        0x44 => arms(1, 2, 2, 1),
        0x45 => arms(2, 1, 1, 2),
        0x46 => arms(1, 2, 1, 2),
        0x47 => arms(2, 2, 2, 1),
        0x48 => arms(2, 2, 1, 2),
        0x49 => arms(2, 1, 2, 2),
        0x4a => arms(1, 2, 2, 2),
        0x4b => arms(2, 2, 2, 2),
        // Double lines (U+2550..U+256C).
        0x50 => arms(3, 3, 0, 0),
        0x51 => arms(0, 0, 3, 3),
        0x52 => arms(0, 3, 0, 1),
        0x53 => arms(0, 1, 0, 3),
        0x54 => arms(0, 3, 0, 3),
        0x55 => arms(3, 0, 0, 1),
        0x56 => arms(1, 0, 0, 3),
        0x57 => arms(3, 0, 0, 3),
        0x58 => arms(0, 3, 1, 0),
        0x59 => arms(0, 1, 3, 0),
        0x5a => arms(0, 3, 3, 0),
        0x5b => arms(3, 0, 1, 0),
        0x5c => arms(1, 0, 3, 0),
        0x5d => arms(3, 0, 3, 0),
        0x5e => arms(0, 3, 1, 1),
        0x5f => arms(0, 1, 3, 3),
        0x60 => arms(0, 3, 3, 3),
        0x61 => arms(3, 0, 1, 1),
        0x62 => arms(1, 0, 3, 3),
        0x63 => arms(3, 0, 3, 3),
        0x64 => arms(3, 3, 0, 1),
        0x65 => arms(1, 1, 0, 3),
        0x66 => arms(3, 3, 0, 3),
        0x67 => arms(3, 3, 1, 0),
        0x68 => arms(1, 1, 3, 0),
        0x69 => arms(3, 3, 3, 0),
        0x6a => arms(3, 3, 1, 1),
        0x6b => arms(1, 1, 3, 3),
        0x6c => arms(3, 3, 3, 3),
        // Rounded corners, drawn square.
        0x6d => arms(0, 1, 0, 1),
        0x6e => arms(1, 0, 0, 1),
        0x6f => arms(1, 0, 1, 0),
        0x70 => arms(0, 1, 1, 0),
        // Half lines.
        0x74 => arms(1, 0, 0, 0),
        0x75 => arms(0, 0, 1, 0),
        0x76 => arms(0, 1, 0, 0),
        0x77 => arms(0, 0, 0, 1),
        0x78 => arms(2, 0, 0, 0),
        0x79 => arms(0, 0, 2, 0),
        0x7a => arms(0, 2, 0, 0),
        0x7b => arms(0, 0, 0, 2),
        0x7c => arms(1, 2, 0, 0),
        0x7d => arms(0, 0, 1, 2),
        0x7e => arms(2, 1, 0, 0),
        0x7f => arms(0, 0, 2, 1),
        _ => return None,
    })
}
