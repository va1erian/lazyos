//! `modplay` (`MODPLAY.ELF`): a ProTracker module player, and the audio
//! stack's showcase client.
//!
//! The file is parsed and mixed in-process by `libs/modplay` (integer only,
//! no I/O) and streamed to the system mixer over `os.lazy.audio.v1` through a
//! blocking [`sink::Sink`]. Row timing comes from the frames mixed, not from
//! sleeping.
//!
//! Usage from the shell: `modplay <file.mod> [loops=<n>] [sep=<0-100>]`, or
//! `modplay selftest`, the built-in single-voice melody the sound harness
//! records and checks (`tools/sound/run.py --modplay`).
//!
//! Serial markers: `MODPLAY:LOAD`, `MODPLAY:PLAY:PASS frames=<n> ...` and
//! `MODPLAY:PLAY:FAIL <reason>`.

#![no_std]
#![no_main]

extern crate alloc;

use alloc::format;
use alloc::string::String;
use alloc::vec;
use core::panic::PanicInfo;

use modplay::{Module, Options, Player};
use user::{files, sys};

#[path = "modplay/sink.rs"]
mod sink;

use sink::Sink;

/// The harness's single-voice melody, generated by
/// `libs/modplay/examples/gen_selftest.rs`.
static SELFTEST: &[u8] = include_bytes!("modplay/selftest.mod");

/// Frames mixed per `render` call: one driver period.
const CHUNK_FRAMES: usize = 2048;
/// Largest module file accepted (the format tops out near 2 MiB).
const MAX_FILE_BYTES: usize = 4 * 1024 * 1024;

enum Source {
    Selftest,
    File(String),
}

struct Args {
    source: Source,
    options: Options,
}

const USAGE: &str =
    "usage: modplay <file.mod> [loops=<n>] [sep=<0-100>]\n       modplay selftest\n";

fn parse_args() -> Option<Args> {
    let mut buffer = [0u8; 256];
    let len = sys::service_args(&mut buffer).min(buffer.len());
    let text = core::str::from_utf8(&buffer[..len]).unwrap_or("");
    let mut source = None;
    let mut options = Options::default();
    for part in text.split_whitespace() {
        match part.split_once('=') {
            // Bounded so a typo cannot ask for hours of playback.
            Some(("loops", n)) => options.loops = Some(n.parse().unwrap_or(1).clamp(1, 100)),
            Some(("sep", n)) => options.separation = n.parse().unwrap_or(70).min(100),
            Some(_) => {}
            None if part == "selftest" => source = Some(Source::Selftest),
            None if part == "-h" || part == "--help" => return None,
            None => source = Some(Source::File(String::from(part))),
        }
    }
    source.map(|source| Args { source, options })
}

#[no_mangle]
pub extern "C" fn _start() -> ! {
    let Some(mut args) = parse_args() else {
        sys::write_str(USAGE);
        sys::exit(0)
    };
    // The self-test is judged from the recording's pitch, so keep the voice on
    // one side: no bleed from neighbouring channels, no interpolation.
    if matches!(args.source, Source::Selftest) {
        args.options.separation = 100;
        args.options.interpolate = false;
    }
    match play(&args) {
        Ok(()) => sys::exit(0),
        Err(reason) => {
            sys::write_str(&format!("MODPLAY:PLAY:FAIL {reason}\n"));
            sys::exit(1)
        }
    }
}

fn load(source: &Source) -> Result<(Module, String), String> {
    let bytes = match source {
        Source::Selftest => vec::Vec::from(SELFTEST),
        Source::File(path) => {
            let bytes = files::read_all(path).map_err(|errno| format!("{path}: errno {errno}"))?;
            if bytes.len() > MAX_FILE_BYTES {
                return Err(format!("{path}: file too large"));
            }
            bytes
        }
    };
    let module = Module::parse(&bytes).map_err(|error| format!("not a module: {error:?}"))?;
    let title = String::from_utf8_lossy(&module.title)
        .trim_end_matches('\0')
        .trim()
        .into();
    Ok((module, title))
}

fn play(args: &Args) -> Result<(), String> {
    let (module, title) = load(&args.source)?;
    sys::write_str(&format!(
        "MODPLAY:LOAD title=\"{title}\" orders={} patterns={}\n",
        module.orders.len(),
        module.pattern_count()
    ));
    let mut sink = Sink::open()?;
    let mut player = Player::new(&module, sink.rate(), args.options);
    let mut buf = vec![0i16; CHUNK_FRAMES * 2];
    loop {
        let frames = player.render(&mut buf);
        if frames == 0 {
            break;
        }
        sink.write(&buf[..frames * 2])?;
    }
    let rate = sink.rate();
    let queued = sink.frames();
    let played = sink.finish()?;
    if played != queued {
        return Err(format!("driver played {played} of {queued} frames"));
    }
    sys::write_str(&format!(
        "MODPLAY:PLAY:PASS frames={played} rate={rate} unsupported_effects={}\n",
        player.unsupported_effects()
    ));
    Ok(())
}

#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    sys::exit(1)
}
