//! The registers and fields the chip code touches (upstream `reg.h`,
//! `rtw8822c.h`, `bf.h`), under upstream's names so the C and the Rust read
//! alike. MAC-side registers the core also uses are duplicated here on
//! purpose: the chip package keeps its own copies (`spec.rs` belongs to the
//! MAC package).

#![allow(dead_code)]

pub const fn bit(n: u32) -> u32 {
    1 << n
}

pub const fn genmask(hi: u32, lo: u32) -> u32 {
    ((!0u32) >> (31 - hi)) & ((!0u32) << lo)
}

