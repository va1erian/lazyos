//! CRC-32 (IEEE 802.3, reflected, as zlib and PNG use it).
//!
//! The bond file is small, so the bitwise form is plenty and needs no table.

pub fn crc32(data: &[u8]) -> u32 {
    let mut crc = !0u32;
    for &byte in data {
        crc ^= u32::from(byte);
        for _ in 0..8 {
            crc = if crc & 1 != 0 {
                crc >> 1 ^ 0xEDB8_8320
            } else {
                crc >> 1
            };
        }
    }
    !crc
}
