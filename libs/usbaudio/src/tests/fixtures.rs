/// A UAC 2.0 high-speed asynchronous DAC: one programmable clock (0x29),
/// 24-in-32 and 16-bit alternates, each with an explicit feedback endpoint.
pub(crate) fn uac2_dac() -> Vec<u8> {
    let general = [
        0x10, 0x24, 0x01, 0x02, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00,
        0x00,
    ];
    let cs_endpoint = [0x08, 0x25, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00];
    let feedback = [0x07, 0x05, 0x81, 0x11, 0x04, 0x00, 0x04];
    config(&[
        &[0x08, 0x0B, 0x00, 0x02, 0x01, 0x00, 0x20, 0x00],
        &[0x09, 0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00],
        &[0x09, 0x24, 0x01, 0x00, 0x02, 0x08, 0x40, 0x00, 0x00],
        &[0x08, 0x24, 0x0A, 0x29, 0x03, 0x07, 0x00, 0x00],
        &[
            0x11, 0x24, 0x02, 0x02, 0x01, 0x01, 0x00, 0x29, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00,
        ],
        &[
            0x12, 0x24, 0x06, 0x0A, 0x02, 0x0F, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
            0x00, 0x00, 0x00, 0x00,
        ],
        &[
            0x0C, 0x24, 0x03, 0x14, 0x01, 0x03, 0x00, 0x0A, 0x29, 0x00, 0x00, 0x00,
        ],
        &[0x09, 0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00],
        &[0x09, 0x04, 0x01, 0x01, 0x02, 0x01, 0x02, 0x20, 0x00],
        &general,
        &[0x06, 0x24, 0x02, 0x01, 0x04, 0x18],
        &[0x07, 0x05, 0x01, 0x05, 0xC8, 0x00, 0x01],
        &cs_endpoint,
        &feedback,
        &[0x09, 0x04, 0x01, 0x02, 0x02, 0x01, 0x02, 0x20, 0x00],
        &general,
        &[0x06, 0x24, 0x02, 0x01, 0x02, 0x10],
        &[0x07, 0x05, 0x01, 0x05, 0x64, 0x00, 0x01],
        &cs_endpoint,
        &feedback,
    ])
}

/// The DAC's clock answering `GET_RANGE`: 44.1, 48, 96 and 192 kHz.
pub(crate) fn dac_range_reply() -> Vec<u8> {
    let mut reply = alloc::vec![4, 0];
    for rate in [44100u32, 48000, 96000, 192000] {
        for value in [rate, rate, 0] {
            reply.extend_from_slice(&value.to_le_bytes());
        }
    }
    reply
}
