//! Configuration descriptors as devices send them. `HS_CONFIG` and
//! `SS_CONFIG` follow QEMU's `usb-storage` (hw/usb/dev-storage.c: one
//! interface 08/06/50, bulk-IN 0x81 and bulk-OUT 0x02, 512 bytes on high
//! speed, 1024 with a companion on SuperSpeed); the OUT burst is 3 here so a
//! test can tell the two companions apart. `KBD_CONFIG` is QEMU's
//! `usb-kbd`; `COMPOSITE_CONFIG` puts a keyboard interface first.

pub const HS_CONFIG: [u8; 32] = [
    0x09, 0x02, 0x20, 0x00, 0x01, 0x01, 0x00, 0xC0, 0x32, // configuration
    0x09, 0x04, 0x00, 0x00, 0x02, 0x08, 0x06, 0x50, 0x00, // interface 0
    0x07, 0x05, 0x81, 0x02, 0x00, 0x02, 0x00, // bulk IN 512
    0x07, 0x05, 0x02, 0x02, 0x00, 0x02, 0x00, // bulk OUT 512
];

pub const SS_CONFIG: [u8; 44] = [
    0x09, 0x02, 0x2C, 0x00, 0x01, 0x01, 0x00, 0xC0, 0x32, // configuration
    0x09, 0x04, 0x00, 0x00, 0x02, 0x08, 0x06, 0x50, 0x00, // interface 0
    0x07, 0x05, 0x81, 0x02, 0x00, 0x04, 0x00, // bulk IN 1024
    0x06, 0x30, 0x0F, 0x00, 0x00, 0x00, // companion, burst 16
    0x07, 0x05, 0x02, 0x02, 0x00, 0x04, 0x00, // bulk OUT 1024
    0x06, 0x30, 0x03, 0x00, 0x00, 0x00, // companion, burst 4
];

pub const KBD_CONFIG: [u8; 34] = [
    0x09, 0x02, 0x22, 0x00, 0x01, 0x01, 0x00, 0xA0, 0x32, // configuration
    0x09, 0x04, 0x00, 0x00, 0x01, 0x03, 0x01, 0x01, 0x00, // HID boot keyboard
    0x09, 0x21, 0x11, 0x01, 0x00, 0x01, 0x22, 0x3F, 0x00, // HID
    0x07, 0x05, 0x81, 0x03, 0x08, 0x00, 0x07, // interrupt IN
];

pub const COMPOSITE_CONFIG: [u8; 57] = [
    0x09, 0x02, 0x39, 0x00, 0x02, 0x01, 0x00, 0xA0, 0x32, // configuration
    0x09, 0x04, 0x00, 0x00, 0x01, 0x03, 0x01, 0x01, 0x00, // HID boot keyboard
    0x09, 0x21, 0x11, 0x01, 0x00, 0x01, 0x22, 0x3F, 0x00, // HID
    0x07, 0x05, 0x81, 0x03, 0x08, 0x00, 0x07, // interrupt IN
    0x09, 0x04, 0x01, 0x00, 0x02, 0x08, 0x06, 0x50, 0x00, // interface 1: BOT
    0x07, 0x05, 0x83, 0x02, 0x40, 0x00, 0x00, // bulk IN 64 (full speed)
    0x07, 0x05, 0x04, 0x02, 0x40, 0x00, 0x00, // bulk OUT 64
];
